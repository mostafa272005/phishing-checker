"""Train the PhishGuard AI model.

Run once:  python train_model.py
It builds a labeled demo dataset, trains a Logistic Regression model,
prints the accuracy, and saves the model to model.joblib.

NOTE: the dataset is generated by this script (synthetic demo data),
not a real-world collection of phishing links.
"""
import random

import joblib
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from features import extract_features

random.seed(42)

LEGIT_DOMAINS = [
    "google.com", "github.com", "wikipedia.org", "microsoft.com", "amazon.com",
    "youtube.com", "stackoverflow.com", "python.org", "cloudflare.com", "bbc.com",
    "linkedin.com", "apple.com", "mozilla.org", "reddit.com", "medium.com",
    "nytimes.com", "dropbox.com", "paypal.com", "netflix.com", "zoom.us",
]
LEGIT_SUBS = ["", "", "", "www.", "docs.", "mail.", "support.", "blog."]
LEGIT_PATHS = [
    "", "/", "/about", "/docs/intro", "/search?q=cloud+computing", "/news/2026/10/article",
    "/login", "/account/settings", "/products/laptops", "/help/contact", "/download",
    "/watch?v=abc123", "/wiki/Cloud_computing", "/pricing", "/user/profile",
]
BRANDS = ["paypal", "google", "microsoft", "amazon", "apple", "netflix", "facebook", "bank", "instagram", "dhl"]
BAIT = ["login", "verify", "secure", "account", "update", "confirm", "signin", "wallet", "billing", "password"]
BAD_TLDS = ["xyz", "top", "tk", "ml", "ga", "cf", "click", "work", "support", "com", "net", "info"]
RAND = "abcdefghijklmnopqrstuvwxyz0123456789"


def rnd(n):
    return "".join(random.choice(RAND) for _ in range(n))


SMALL_SHOPS = ["my-shop", "online-store", "city-news", "best-recipes", "travel-blog", "cairo-tech", "student-hub", "fit-life"]
SHOP_TLDS = ["com", "org", "net", "info", "co", "io", "xyz", "top"]
SHOP_PATHS = ["", "/", "/products", "/login", "/account", "/blog/post-12", "/shop?cat=3&page=2", "/contact", "/secure-checkout"]


def make_legit():
    # Real-world look-alikes: small sites with hyphens, odd TLDs, http, login pages.
    if random.random() < 0.25:
        scheme = "https://" if random.random() < 0.7 else "http://"
        return scheme + random.choice(SMALL_SHOPS) + "." + random.choice(SHOP_TLDS) + random.choice(SHOP_PATHS)
    scheme = "https://" if random.random() < 0.9 else "http://"
    domain = random.choice(LEGIT_DOMAINS)
    return scheme + random.choice(LEGIT_SUBS) + domain + random.choice(LEGIT_PATHS)


def make_phish():
    # Harder phishing: short, clean-looking links with no obvious bait words.
    if random.random() < 0.2:
        scheme = "https://" if random.random() < 0.6 else "http://"
        return scheme + random.choice(BRANDS) + rnd(random.randint(2, 4)) + "." + random.choice(BAD_TLDS) + random.choice(["", "/", "/" + rnd(6)])
    scheme = "http://" if random.random() < 0.7 else "https://"
    brand = random.choice(BRANDS)
    bait = random.choice(BAIT)
    tld = random.choice(BAD_TLDS)
    kind = random.randint(1, 5)
    if kind == 1:
        host = ".".join(str(random.randint(1, 254)) for _ in range(4))
        return scheme + host + "/" + bait + "-" + brand + random.choice(["", "/index.php", "/" + rnd(8)])
    if kind == 2:
        return scheme + brand + "-" + bait + "-" + rnd(random.randint(2, 6)) + "." + tld + "/" + bait + random.choice(["", ".php", "?id=" + rnd(10)])
    if kind == 3:
        return scheme + bait + "." + brand + ".com." + rnd(6) + "-" + random.choice(BAIT) + "." + tld + "/" + rnd(12)
    if kind == 4:
        return scheme + brand + ".com@" + rnd(8) + "." + tld + "/" + bait + "/" + rnd(random.randint(10, 30))
    return scheme + "secure-" + brand + "." + rnd(5) + "." + tld + "/" + bait + "?session=" + rnd(24) + "&user=" + rnd(8)


def main():
    legit = [make_legit() for _ in range(700)]
    phish = [make_phish() for _ in range(700)]
    urls = legit + phish
    labels = [0] * len(legit) + [1] * len(phish)

    X = [extract_features(u) for u in urls]
    X_train, X_test, y_train, y_test = train_test_split(
        X, labels, test_size=0.25, random_state=1, stratify=labels
    )
    model = make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000))
    model.fit(X_train, y_train)

    pred = model.predict(X_test)
    print("Training links:", len(X_train), " Test links:", len(X_test))
    print("Accuracy on test links: %.1f%%" % (100 * accuracy_score(y_test, pred)))
    print(classification_report(y_test, pred, target_names=["legit", "phishing"]))

    joblib.dump(model, "model.joblib")
    print("Saved model.joblib")


if __name__ == "__main__":
    main()
